"""Generates app/src/main/res/values/strings.xml (English fallback) and values-zh-rCN/strings.xml
from tools/strings_table.py, so both languages always have the same keys.

Usage: python3 tools/strings.py   (from the repo root; prints keys missing from or unused in code)
"""
import sys, re, os
S = {}
def s(name, en, zh): S[name] = (en, zh)
exec(open(os.path.join(os.path.dirname(__file__), 'strings_table.py'), encoding='utf-8').read())

def esc(t):
    t = t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    t = t.replace("'", "\\'").replace('"', '\\"')
    if t.startswith('@') or t.startswith('?'): t = '\\' + t
    return t

res = sys.argv[1] if len(sys.argv) > 1 else 'app/src/main/res'
src = sys.argv[2] if len(sys.argv) > 2 else 'app/src/main/java'
for folder, idx in (('values', 0), ('values-zh-rCN', 1)):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/strings.py from tools/strings_table.py; edit the table, not this file. -->', '<resources>']
    for name in sorted(S):
        lines.append(f'    <string name="{name}">{esc(S[name][idx])}</string>')
    lines.append('</resources>')
    open(os.path.join(res, folder, 'strings.xml'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

# Report names used in code but missing from the table.
used = set()
for root, _, files in os.walk(src):
    for f in files:
        if f.endswith('.kt'):
            used |= set(re.findall(r'R\.string\.(\w+)', open(os.path.join(root, f), encoding='utf-8').read()))
used.discard('app_name')
missing = sorted(used - set(S))
unused = sorted(set(S) - used)
print('missing:', missing)
print('unused:', unused)
